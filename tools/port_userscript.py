#!/usr/bin/env python3
"""Regenerate static/js/dataweaver.js from the Commons Data Weaver user script.

The web app and the Commons user script share one interface. The few places where the web app
must differ (no overlay "Close" button, opt-in OpenStreetMap search, configurable tile server,
deep-link ?category=, no Tools-menu link) are listed below as exact-text replacements. Each one must
match exactly once, otherwise this script stops and tells you which rule no longer fits.

Usage:  python tools/port_userscript.py path/to/CommonsDataWeaver.js [static/js/dataweaver.js]
"""
import re
import sys
from pathlib import Path

HEADER = '''/**
 * Commons Data Weaver — web application interface (https://dataweaver.toolforge.org/)
 * Source: https://github.com/wikimedia-biodiversity/dataweaver
 * Copyright (C) 2026 Manoj Karingamadathil (https://meta.wikimedia.org/wiki/User:Manojk, ORCID 0000-0003-3885-6595)
 * DOI: 10.5281/zenodo.23680559
 * License: GPL-3.0-or-later (see LICENSE)
 *
 * Generated by tools/port_userscript.py from the Commons Data Weaver user script, which runs on the
 * MediaWiki helpers provided by static/js/dw-shim.js. Edit the user script and regenerate, or edit
 * this file directly and stop running the port script - not both.
 */'''

RULES = [
    # (description, old, new)
    ("web page has no overlay to close",
     "h('button', { class: 'jv-primary', onclick: () => confirmSave(S.recs) }, 'Save all changes'),\n"
     "  h('button', { onclick: () => { root.style.display = 'none'; document.body.style.overflow = ''; } }, 'Close'));",
     "h('button', { class: 'jv-primary', onclick: () => confirmSave(S.recs) }, 'Save all changes'));"),
    ("OpenStreetMap place search is opt-in (privacy)",
     "const [a, b] = await Promise.all([fPlaceWD(q).catch(() => []), fPlaceOSM(q).catch(() => [])]);",
     "const [a, b] = await Promise.all([fPlaceWD(q).catch(() => []), (window.DW && DW.osmEnabled() ? fPlaceOSM(q) : Promise.resolve([])).catch(() => [])]);"),
    ("Nominatim endpoint comes from the server configuration",
     "fetch('https://nominatim.openstreetmap.org/search?format=jsonv2",
     "fetch(DW.config.nominatimUrl + '?format=jsonv2"),
    ("map tile server comes from the server configuration",
     "src: 'https://maps.wikimedia.org/osm-intl/' + z + '/' + (((tx % N) + N) % N) + '/' + ty + '.png'",
     "src: DW.tile(z, ((tx % N) + N) % N, ty)"),
    ("open a category passed as ?category=Name",
     "if (!S.recs.length) loadMyList();",
     "if (!S.recs.length) { if (cfg) listCategory(cfg).then(loadTitles).catch(e => setStatus('Error: ' + e)); else loadMyList(); }"),
]
TAIL_START = "const li = mw.util.addPortletLink("
TAIL_END = "open();"


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1]).read_text(encoding="utf-8")
    out = Path(sys.argv[2] if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "static/js/dataweaver.js")

    end = src.index("*/") + 2
    if not src.lstrip().startswith("/**"):
        sys.exit("The user script must start with a /** header comment.")
    src = HEADER + src[end:]

    problems = []
    for what, old, new in RULES:
        n = src.count(old)
        if n != 1:
            problems.append("%s: expected 1 match, found %d" % (what, n))
        else:
            src = src.replace(old, new)

    i = src.find(TAIL_START)
    j = src.find("\n\n});\n})();", i)
    if i < 0 or j < 0:
        problems.append("entry point block (addPortletLink ... open) not found")
    else:
        src = src[:i] + "/* The web app is always open: there is no Tools-menu link or overlay toggle. */\nopen();" + src[j:]

    if problems:
        sys.exit("The user script changed in a way the port rules do not cover:\n  - " + "\n  - ".join(problems))
    out.write_text(src, encoding="utf-8")
    print("Wrote %s (%d lines, %d rules applied)" % (out, src.count("\n") + 1, len(RULES) + 2))


if __name__ == "__main__":
    main()
